// Functional: ABS-342 structured report deliverable (ReportDocument).
//
// A `captured` purchase renders through one shared ReportDocument template
// in a fixed section order (letterhead → title → meta grid → determination
// band → summary → typed body blocks → verification footer), driven by a
// typed block array. This spec drives the real /app/answers view and stubs
// the purchase proxy at the network boundary (same pattern as the ABS-321
// answer-view spec) with a structured `report` payload, and asserts:
//   - due_diligence exercises keyvals / uses / finding / flags / prose;
//   - development_standards exercises the `table` block with per-row
//     PASS / EXCEEDS status;
//   - the letterhead/footer meta lifted onto the report record renders
//     (issued, prepared-for, zone subtitle, bylaw version, price, footer).

