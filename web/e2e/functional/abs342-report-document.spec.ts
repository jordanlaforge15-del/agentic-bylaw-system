type Purchase = {
  id: number;
  question_slug: string;
  status: string;
  price_cents: number;
  currency: string;
  answer: string | null;
  report: Report | null;
  failure_reason: string | null;
  refinement_count: number;
  refinements_remaining: number;
  window_expires_at: string | null;
};

function purchase(overrides: Partial<Purchase> = {}): Purchase {
  return {
    id: 342,
    question_slug: "due_diligence",
    status: "captured",
    price_cents: 19900,
    currency: "CAD",
    answer: "Raw markdown fallback.",
    report: dueDiligenceReport(),
    failure_reason: null,
    refinement_count: 0,
    refinements_remaining: 3,
    window_expires_at: "2026-12-31T00:00:00Z",
    ...overrides,
  };
}

function json(route: Route, body: unknown, status = 200) {
  return route.fulfill({
    status,
    contentType: "application/json",
    body: JSON.stringify(body),
  });
}

async function stubPurchase(page: Page, get: () => unknown) {
  await page.route(
    /\/api\/billing\/questions\/purchases\/\d+(\/(answer|refine))?$/,
    (route) => json(route, get()),
  );
}

test.describe("structured report deliverable (ABS-342)", () => {
  test("due_diligence renders the full ReportDocument chrome + all block types", async ({
    page,
  }) => {
    await stubPurchase(page, () => purchase());
    await page.goto("/app/answers/342");

    const doc = page.getByTestId("report-document");
    await expect(doc).toBeVisible();

    // Letterhead — report-type + ref.
    await expect(page.getByTestId("report-type")).toContainText(
      /due-diligence/i,
    );
    await expect(page.getByTestId("report-ref")).toHaveText("DD-000342");

    // Title block — address + zone.
    await expect(page.getByTestId("report-address")).toHaveText(
      "1234 Elm Street",
    );
    await expect(page.getByTestId("report-zone")).toHaveText(
      "Established Residential, Type 1",
    );

    // Meta grid — issued · prepared-for · bylaw version · price paid.
    const meta = page.getByTestId("report-meta");
    await expect(meta).toContainText("2026-07-03");
    await expect(meta).toContainText("Jordan Buyer");
    await expect(meta).toContainText(/2024 consolidation/);
    await expect(meta).toContainText("$199.00 CAD");

    // Determination band — status chip + verdict headline.
    await expect(page.getByTestId("report-verdict-chip")).toHaveText(
      "CONDITIONAL",
    );
    await expect(page.getByTestId("report-verdict")).toContainText(
      "Permitted with conditions",
    );

    // Summary.
    await expect(page.getByTestId("report-summary")).toContainText(
      /preliminary zoning due-diligence/i,
    );

    // All five body-block renderers this report exercises.
    await expect(page.getByTestId("block-keyvals")).toContainText("ER-1");
    await expect(page.getByTestId("block-uses")).toContainText(
      "Single detached dwelling",
    );
    await expect(page.getByTestId("block-finding")).toContainText(
      /rear-yard setback/i,
    );
    await expect(page.getByTestId("block-flags")).toContainText(
      /rear setback below the minimum/i,
    );
    await expect(page.getByTestId("block-prose")).toContainText(
      /preliminary aid/i,
    );

    // Verification footer.
    await expect(page.getByTestId("report-footer")).toContainText(
      "DD-000342",
    );

    // The refinement composer still lives below the report.
    await expect(page.getByTestId("refine-remaining")).toContainText(
      /3 FOLLOW-UPS LEFT/i,
    );
  });

  test("development_standards renders the table block with per-row PASS/EXCEEDS", async ({
    page,
  }) => {
    await stubPurchase(page, () =>
      purchase({
        id: 343,
        question_slug: "development_standards",
        price_cents: 14900,
        report: developmentStandardsReport(),
      }),
    );
    await page.goto("/app/answers/343");

    await expect(page.getByTestId("report-document")).toBeVisible();

    const table = page.getByTestId("block-table");
    await expect(table).toBeVisible();
    await expect(table).toContainText("Height");
    await expect(table).toContainText("Front setback");

    // Per-row status tags: the table exercises both PASS and EXCEEDS.
    const statuses = page.getByTestId("row-status");
    await expect(statuses).toHaveCount(3);
    await expect(statuses.filter({ hasText: "PASS" })).toHaveCount(2);
    await expect(statuses.filter({ hasText: "EXCEEDS" })).toHaveCount(1);

    // A clean compliance report carries the favourable (accent) verdict.
    await expect(page.getByTestId("report-verdict-chip")).toHaveText("PASS");
  });

  test("ABS-366: a property-summary table with no evaluation column renders no stray status pill", async ({
    page,
  }) => {
    await stubPurchase(page, () =>
      purchase({
        id: 366,
        question_slug: "permitted_use",
        price_cents: 9900,
        report: propertySummaryReport(),
      }),
    );
    await page.goto("/app/answers/366");

    const table = page.getByTestId("block-table");
    await expect(table).toBeVisible();
    await expect(table).toContainText("Governing By-law");
    await expect(table).toContainText("Regional Centre Land Use By-Law");

    // Non-status rows (Zone, Governing By-law) must never carry a pill.
    await expect(page.getByTestId("row-status")).toHaveCount(0);
    await expect(table).not.toContainText("FAIL");
  });

  test("ABS-373: N/A / not-regulated rows in an evaluation table render no pill, genuine FAIL stays", async ({
    page,
  }) => {
    await stubPurchase(page, () =>
      purchase({
        id: 373,
        question_slug: "development_standards",
        price_cents: 14900,
        report: naVerdictReport(),
      }),
    );
    await page.goto("/app/answers/373");

    await expect(page.getByTestId("report-document")).toBeVisible();

    // Both the built-form table and the summary table carry Lot Coverage /
    // FAR rows whose verdict is N/A. Neither may render a status pill — even
    // though "Lot Coverage" contains the substring "over".
    const rows = page.getByTestId("table-row");
    const lotCoverageRows = rows.filter({ hasText: "Lot Coverage" });
    await expect(lotCoverageRows).toHaveCount(2);
    for (let i = 0; i < 2; i++) {
      await expect(
        lotCoverageRows.nth(i).getByTestId("row-status"),
      ).toHaveCount(0);
      await expect(lotCoverageRows.nth(i)).not.toContainText("FAIL");
    }

    // The FAR rows (same N/A verdict) are likewise pill-free.
    const farRows = rows.filter({ hasText: "FAR" });
    await expect(farRows).toHaveCount(2);
    for (let i = 0; i < 2; i++) {
      await expect(farRows.nth(i).getByTestId("row-status")).toHaveCount(0);
    }

    // A genuinely failing row still shows its FAIL pill — the fix is targeted,
    // not a blanket suppression of all row status.
    const failRow = rows.filter({ hasText: "Rear setback" });
    await expect(failRow.getByTestId("row-status")).toHaveText("FAIL");

    // Exactly two pills total across the report: the PASS (Height) and the
    // FAIL (Rear setback) rows — the four N/A rows contribute none.
    await expect(page.getByTestId("row-status")).toHaveCount(2);
  });

  test("falls back to raw markdown when no structured report is present", async ({
    page,
  }) => {
    await stubPurchase(page, () =>
      purchase({
        report: null,
        answer: "Based on the bylaw evidence, the use is permitted.",
      }),
    );
    await page.goto("/app/answers/342");

    await expect(page.getByTestId("report-document")).toHaveCount(0);
    await expect(page.getByTestId("answer-body")).toContainText(
      /Based on the bylaw evidence/i,
    );
  });
});
